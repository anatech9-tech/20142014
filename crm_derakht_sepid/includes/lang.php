// Translation function
function t($key, $fallback = null) {
    global $translations, $lang;
    if (isset($translations[$lang][$key])) return $translations[$lang][$key];
    if ($fallback !== null) return $fallback;
    // Legacy UI literals are kept in a separate catalog while older pages are migrated.
    global $legacy_translations;
    if (isset($legacy_translations[$lang][$key])) return $legacy_translations[$lang][$key];
    // Fallback to Farsi
    if (isset($translations['fa'][$key])) return $translations['fa'][$key];
    return $key;
}

